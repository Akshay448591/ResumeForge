import {
  ArrowRight,
  Check,
  ChevronDown,
  ChevronLeft,
  ChevronRight,
  ChevronUp,
  CircleAlert,
  Copy,
  Download,
  Eye,
  EyeOff,
  FileText,
  History,
  Info,
  LayoutDashboard,
  LayoutTemplate,
  LogOut,
  Maximize2,
  Minus,
  Pencil,
  Plus,
  Search,
  Settings,
  Sparkles,
  Target,
  Trash2,
  Upload,
  X,
  type LucideIcon,
} from 'lucide-react';

const ICONS = {
  plus: Plus,
  trash: Trash2,
  copy: Copy,
  up: ChevronUp,
  down: ChevronDown,
  eye: Eye,
  eyeOff: EyeOff,
  edit: Pencil,
  search: Search,
  check: Check,
  x: X,
  file: FileText,
  minus: Minus,
  upload: Upload,
  download: Download,
  sparkles: Sparkles,
  settings: Settings,
  templates: LayoutTemplate,
  dashboard: LayoutDashboard,
  logout: LogOut,
  alert: CircleAlert,
  info: Info,
  left: ChevronLeft,
  right: ChevronRight,
  arrowRight: ArrowRight,
  history: History,
  maximize: Maximize2,
  target: Target,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof ICONS;

export function Icon({ name, className = 'h-4 w-4' }: { name: IconName; className?: string }) {
  const Glyph = ICONS[name];
  return <Glyph className={className} strokeWidth={1.75} aria-hidden="true" />;
}
